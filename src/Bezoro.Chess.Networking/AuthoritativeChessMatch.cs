using Bezoro.Chess.UCI.Protocol.API;
using Bezoro.Chess.UCI.Protocol.API.Types;

namespace Bezoro.Chess.Networking;

/// <summary>The outcome of an asynchronous engine turn.</summary>
/// <param name="Applied">Whether the returned move was committed to the captured position.</param>
/// <param name="Snapshot">Current authoritative state, including a newer position when the request became obsolete.</param>
public readonly record struct ChessEngineTurnResult(bool Applied, ChessMatchSnapshot Snapshot);

/// <summary>A small transport-independent command boundary around a private, locally validated chess match.</summary>
/// <remarks>
/// The host authenticates each connection and maps it to a seat; never accept a seat supplied by the client as proof of identity.
/// Public operations serialize state access. Only the configured engine seat may receive engine moves.
/// No sockets, polling loop, tasks, or engine processes are created during local play.
/// </remarks>
public sealed class AuthoritativeChessMatch : IDisposable
{
    private readonly object _gate = new();
    private readonly UciPlayableMatchSession _match;
    private readonly Guid _matchId;
    private readonly Fen _baseFen;
    private readonly bool _allowTakebacks;
    private readonly ChessPlayerSeat? _engineSeat;
    private readonly int _maximumHalfmoves;
    private long _revision;
    private ChessMatchSnapshot _snapshot;
    private ChessTakebackOffer? _takebackOffer;
    private AcceptedCommand? _whiteLast;
    private AcceptedCommand? _blackLast;
    private CancellationTokenSource? _engineCancellation;
    private bool _disposed;

    /// <summary>Creates and validates a match. Takebacks are opt-in; the default history budget is 4096 halfmoves.</summary>
    /// <param name="matchId">Nonempty identity generated by the host, never reused for another game.</param>
    /// <param name="setup">Starting position and complete saved move history.</param>
    /// <param name="timeControl">Optional authoritative clocks.</param>
    /// <param name="allowTakebacks">Whether both players may agree to restore previous positions, including after a result.</param>
    /// <param name="engineSeat">Optional computer-controlled seat; peer commands cannot impersonate it.</param>
    /// <param name="maximumHalfmoves">Host resource limit for the complete retained move history.</param>
    /// <param name="utcNowProvider">Optional clock source; use a monotonic elapsed-time source for server clocks.</param>
    public AuthoritativeChessMatch(
        Guid matchId,
        PlayableMatchSetup setup,
        PlayableMatchTimeControl? timeControl = null,
        bool allowTakebacks = false,
        ChessPlayerSeat? engineSeat = null,
        int maximumHalfmoves = 4096,
        Func<DateTimeOffset>? utcNowProvider = null)
    {
        if (matchId == Guid.Empty) throw new ArgumentException("A host-assigned match identity is required.", nameof(matchId));
        if (maximumHalfmoves <= 0) throw new ArgumentOutOfRangeException(nameof(maximumHalfmoves));
        if (engineSeat.HasValue) ValidateSeat(engineSeat.Value);
        if (setup.PlayedMoves.IsDefault || setup.PlayedMoves.Length > maximumHalfmoves)
            throw new ArgumentException("The initialized setup must fit the host's history budget.", nameof(setup));
        setup.Validate();
        _matchId = matchId;
        _baseFen = setup.BaseFen;
        _allowTakebacks = allowTakebacks;
        _engineSeat = engineSeat;
        _maximumHalfmoves = maximumHalfmoves;
        _match = new UciPlayableMatchSession(
            claimableDrawPolicy: PlayableMatchClaimableDrawPolicy.ClaimRequired,
            drawOfferPolicy: PlayableMatchDrawOfferPolicy.ExpireOnMove,
            timeControl: timeControl,
            utcNowProvider: utcNowProvider);
        try
        {
            // Local loading completes synchronously and never contacts an engine.
            _match.LoadMatchAsync(setup).GetAwaiter().GetResult();
            _snapshot = new(_matchId, 0, _baseFen, _match.CurrentState, null);
        }
        catch { _match.Dispose(); throw; }
    }

    /// <summary>Refreshes authoritative clocks and results without computing engine analysis.</summary>
    public ChessMatchSnapshot GetSnapshot()
    {
        CancellationTokenSource? obsolete;
        ChessMatchSnapshot snapshot;
        lock (_gate)
        {
            ThrowIfDisposed();
            long before = _revision;
            RefreshLocked();
            snapshot = _snapshot;
            obsolete = before == _revision ? null : _engineCancellation;
        }
        CancelRequest(obsolete);
        return snapshot;
    }

    /// <summary>Validates an authenticated player's action against the current authoritative revision.</summary>
    /// <remarks>
    /// Only accepted commands consume a sequence. Start at one and increment by one after acceptance.
    /// The last accepted command and receipt per seat are retained for bounded idempotent redelivery; older requests are rejected.
    /// A duplicate receipt can have an older revision than a subsequently received snapshot; clients must keep their newest revision.
    /// </remarks>
    public ChessMatchCommandReceipt Submit(ChessPlayerSeat authenticatedSeat, ChessMatchCommand command)
    {
        ValidateSeat(authenticatedSeat);
        CancellationTokenSource? obsolete = null;
        ChessMatchCommandReceipt receipt;
        lock (_gate)
        {
            ThrowIfDisposed();
            long before = _revision;
            RefreshLocked();
            try { receipt = SubmitLocked(authenticatedSeat, command); }
            catch (InvalidOperationException) when (_match.Refresh().Result.IsTerminal)
            {
                // A server clock can expire between validation and the action's own timestamp.
                RefreshLocked();
                receipt = new(ChessMatchCommandStatus.MatchFinished, command.Sequence, _snapshot);
            }
            if (before != _revision) obsolete = _engineCancellation;
        }
        CancelRequest(obsolete);
        return receipt;
    }

    /// <summary>Restores halfmoves in an opted-in casual engine game and invalidates an outstanding engine reply.</summary>
    /// <remarks>This is a host operation. Authenticate and authorize a human request before calling it. Two-player games require the takeback command/consent flow instead.</remarks>
    public ChessMatchSnapshot TakebackEngineGame(int halfmoves = 2)
    {
        CancellationTokenSource? obsolete;
        ChessMatchSnapshot snapshot;
        lock (_gate)
        {
            ThrowIfDisposed();
            if (!_allowTakebacks || !_engineSeat.HasValue)
                throw new InvalidOperationException("Host-authorized takebacks require an opted-in casual engine game.");
            if (_revision == long.MaxValue) throw new InvalidOperationException("The match revision space is exhausted.");
            _match.UndoMoves(halfmoves);
            _takebackOffer = null;
            AdvanceRevisionLocked();
            snapshot = _snapshot;
            obsolete = _engineCancellation;
        }
        CancelRequest(obsolete);
        return snapshot;
    }

    /// <summary>Requests one engine move outside the state lock, applying it only if its captured revision remains current.</summary>
    /// <remarks>
    /// Call on the authoritative host using its own finite search budget. At most one engine request may be outstanding.
    /// State changes and disposal signal cancellation; services that ignore cancellation still cannot apply stale moves.
    /// The caller owns the service, its transport, and its engine processes.
    /// </remarks>
    public async Task<ChessEngineTurnResult> PlayEngineTurnAsync(
        IChessMoveService service, SearchParameters search, CancellationToken ct = default)
    {
        if (service is null) throw new ArgumentNullException(nameof(service));
        UciChessMoveService.ValidateFiniteSearch(search);
        ChessEnginePosition position;
        CancellationTokenSource cancellation;
        lock (_gate)
        {
            ThrowIfDisposed();
            ct.ThrowIfCancellationRequested();
            RefreshLocked();
            if (!_engineSeat.HasValue || Side(_engineSeat.Value) != _snapshot.State.Fen.ActiveColor)
                throw new InvalidOperationException("The active seat is not controlled by an engine.");
            if (_snapshot.State.Result.IsTerminal)
                throw new InvalidOperationException("The match is finished.");
            if (_snapshot.State.MoveHistory.Length >= _maximumHalfmoves)
                throw new InvalidOperationException("The host's move-history budget was reached.");
            if (_engineCancellation is not null)
                throw new InvalidOperationException("An engine turn is already outstanding.");
            cancellation = CancellationTokenSource.CreateLinkedTokenSource(ct);
            _engineCancellation = cancellation;
            position = _snapshot.CreateEnginePosition();
        }
        try
        {
            string move = await service.FindMoveAsync(position, search, cancellation.Token).ConfigureAwait(false);
            ct.ThrowIfCancellationRequested();
            lock (_gate)
            {
                ThrowIfDisposed();
                ct.ThrowIfCancellationRequested();
                RefreshLocked();
                if (position.Revision != _revision || _snapshot.State.Result.IsTerminal)
                    return new(false, _snapshot);
                if (!IsLegalMoveLocked(move))
                    throw new InvalidOperationException("The engine service returned an illegal or incomplete move.");
                try { ApplyMoveLocked(move); }
                catch (InvalidOperationException) when (_match.Refresh().Result.IsTerminal)
                {
                    RefreshLocked();
                    return new(false, _snapshot);
                }
                AdvanceRevisionLocked();
                return new(true, _snapshot);
            }
        }
        finally
        {
            lock (_gate)
                if (ReferenceEquals(_engineCancellation, cancellation)) _engineCancellation = null;
            cancellation.Dispose();
        }
    }

    /// <summary>Releases local match state and cancels an outstanding engine request. No caller-owned services are disposed.</summary>
    public void Dispose()
    {
        CancellationTokenSource? cancellation;
        lock (_gate)
        {
            if (_disposed) return;
            _disposed = true;
            cancellation = _engineCancellation;
            _match.Dispose();
            _whiteLast = _blackLast = null;
            _snapshot = default;
        }
        CancelRequest(cancellation);
    }

    private ChessMatchCommandReceipt SubmitLocked(ChessPlayerSeat seat, ChessMatchCommand command)
    {
        ChessMatchCommandReceipt Reject(ChessMatchCommandStatus status) => new(status, command.Sequence, _snapshot);
        if (command.MatchId != _matchId) return Reject(ChessMatchCommandStatus.WrongMatch);
        if (seat == _engineSeat) return Reject(ChessMatchCommandStatus.NotAuthorized);
        var previous = seat == ChessPlayerSeat.White ? _whiteLast : _blackLast;
        if (previous.HasValue && previous.Value.Command == command) return previous.Value.Receipt;
        long lastSequence = previous?.Command.Sequence ?? 0;
        if (lastSequence == long.MaxValue || command.Sequence != lastSequence + 1)
            return Reject(ChessMatchCommandStatus.InvalidSequence);
        if (command.ExpectedRevision != _revision) return Reject(ChessMatchCommandStatus.StaleRevision);
        bool takebackAction = command.Kind is ChessMatchCommandKind.RequestTakeback or
            ChessMatchCommandKind.AcceptTakeback or ChessMatchCommandKind.DeclineTakeback;
        if (_snapshot.State.Result.IsTerminal && !takebackAction) return Reject(ChessMatchCommandStatus.MatchFinished);
        if (command.Kind is ChessMatchCommandKind.Move or ChessMatchCommandKind.ClaimDraw &&
            Side(seat) != _snapshot.State.Fen.ActiveColor)
            return Reject(ChessMatchCommandStatus.NotAuthorized);
        if (_revision == long.MaxValue) throw new InvalidOperationException("The match revision space is exhausted.");

        switch (command.Kind)
        {
            case ChessMatchCommandKind.Move:
                if (_snapshot.State.MoveHistory.Length >= _maximumHalfmoves)
                    return Reject(ChessMatchCommandStatus.MoveLimitReached);
                if (!IsLegalMoveLocked(command.Move)) return Reject(ChessMatchCommandStatus.InvalidAction);
                ApplyMoveLocked(command.Move!);
                break;
            case ChessMatchCommandKind.Resign:
                _match.Resign(Side(seat));
                _takebackOffer = null;
                break;
            case ChessMatchCommandKind.OfferDraw:
                if (_snapshot.State.DrawOfferedBy.HasValue) return Reject(ChessMatchCommandStatus.InvalidAction);
                _match.OfferDraw(Side(seat));
                break;
            case ChessMatchCommandKind.AcceptDraw:
            case ChessMatchCommandKind.DeclineDraw:
                if (!_snapshot.State.DrawOfferedBy.HasValue || _snapshot.State.DrawOfferedBy == Side(seat))
                    return Reject(ChessMatchCommandStatus.NotAuthorized);
                if (command.Kind == ChessMatchCommandKind.AcceptDraw) _match.AcceptDraw(Side(seat));
                else _match.DeclineDraw(Side(seat));
                _takebackOffer = null;
                break;
            case ChessMatchCommandKind.ClaimDraw:
                if (command.Move is null)
                {
                    if (!_snapshot.State.ClaimableResult.HasValue) return Reject(ChessMatchCommandStatus.InvalidAction);
                    _match.ClaimDraw();
                }
                else
                {
                    if (!IsLegalMoveLocked(command.Move) || !_match.CanClaimDraw(command.Move))
                        return Reject(ChessMatchCommandStatus.InvalidAction);
                    _match.ClaimDraw(command.Move);
                }
                _takebackOffer = null;
                break;
            case ChessMatchCommandKind.RequestTakeback:
                if (!_allowTakebacks || _engineSeat.HasValue) return Reject(ChessMatchCommandStatus.NotAuthorized);
                if (_takebackOffer.HasValue || command.TakebackHalfmoves <= 0 || !_match.CanUndoMoves(command.TakebackHalfmoves))
                    return Reject(ChessMatchCommandStatus.InvalidAction);
                _takebackOffer = new(seat, command.TakebackHalfmoves);
                break;
            case ChessMatchCommandKind.AcceptTakeback:
            case ChessMatchCommandKind.DeclineTakeback:
                if (!_allowTakebacks || !_takebackOffer.HasValue || _takebackOffer.Value.OfferedBy == seat)
                    return Reject(ChessMatchCommandStatus.NotAuthorized);
                if (command.Kind == ChessMatchCommandKind.AcceptTakeback) _match.UndoMoves(_takebackOffer.Value.Halfmoves);
                _takebackOffer = null;
                break;
            default: return Reject(ChessMatchCommandStatus.InvalidAction);
        }
        AdvanceRevisionLocked();
        var receipt = new ChessMatchCommandReceipt(ChessMatchCommandStatus.Accepted, command.Sequence, _snapshot);
        var accepted = new AcceptedCommand(command, receipt);
        if (seat == ChessPlayerSeat.White) _whiteLast = accepted;
        else _blackLast = accepted;
        return receipt;
    }

    private bool IsLegalMoveLocked(string? move)
    {
        if (move is null) return false;
        foreach (string legal in _snapshot.State.LegalMoves)
            if (string.Equals(legal, move, StringComparison.Ordinal)) return true;
        return false;
    }

    private void ApplyMoveLocked(string move)
    {
        _match.ApplyMove(move);
        _takebackOffer = null;
    }

    private void RefreshLocked()
    {
        var state = _match.Refresh();
        if (state.Result != _snapshot.State.Result) IncrementRevision();
        _snapshot = new(_matchId, _revision, _baseFen, state, _takebackOffer);
    }

    private void AdvanceRevisionLocked()
    {
        IncrementRevision();
        _snapshot = new(_matchId, _revision, _baseFen, _match.Refresh(), _takebackOffer);
    }

    private void IncrementRevision() => _revision = checked(_revision + 1);
    private void ThrowIfDisposed() { if (_disposed) throw new ObjectDisposedException(nameof(AuthoritativeChessMatch)); }
    private static char Side(ChessPlayerSeat seat) => seat == ChessPlayerSeat.White ? 'w' : 'b';
    private static void ValidateSeat(ChessPlayerSeat seat)
    {
        if (seat is not (ChessPlayerSeat.White or ChessPlayerSeat.Black)) throw new ArgumentOutOfRangeException(nameof(seat));
    }

    private static void CancelRequest(CancellationTokenSource? cancellation)
    {
        if (cancellation is null) return;
        try { cancellation.Cancel(); }
        catch (ObjectDisposedException) { } // Completion may have disposed it after the state lock was released.
        catch (AggregateException) { } // A service's cancellation callback must not turn a committed move into a failed command.
    }

    private readonly record struct AcceptedCommand(ChessMatchCommand Command, ChessMatchCommandReceipt Receipt);
}
